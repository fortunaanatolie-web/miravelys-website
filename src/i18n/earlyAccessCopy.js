export function resolveEarlyAccessCopy(lang, delivery = 'email') {
  const copy = byLanguage[lang] ?? byLanguage.en;
  return delivery === 'endpoint'
    ? {
      ...copy,
      ...copy.endpoint,
      success: copy.endpoint?.success ?? byLanguage.en.endpoint.success,
      delivery,
    }
    : { ...copy, delivery: 'email' };
}
